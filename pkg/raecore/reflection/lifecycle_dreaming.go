// ConsolidationStage enumerates the 7-state memory consolidation lifecycle FSM
// from apps/memory_api/services/memory_consolidation.py.
type ConsolidationStage string

const (
	StageNew           ConsolidationStage = "NEW"
	StageActive        ConsolidationStage = "ACTIVE"
	StageConsolidating ConsolidationStage = "CONSOLIDATING"
	StageConsolidated  ConsolidationStage = "CONSOLIDATED"
	StageDecaying      ConsolidationStage = "DECAYING"
	StageArchived      ConsolidationStage = "ARCHIVED"
	StagePruned        ConsolidationStage = "PRUNED"
)

// MemoryLifecycleRecord tracks a memory item's 7-state consolidation FSM history.
type MemoryLifecycleRecord struct {
	MemoryID     string               `json:"memory_id"`
	CurrentStage ConsolidationStage   `json:"current_stage"`
	TargetLayer  models.MemoryLayer   `json:"target_layer"`
	Importance   float64              `json:"importance"`
	Strength     float64              `json:"strength"`
	UsageCount   int                  `json:"usage_count"`
	History      []ConsolidationStage `json:"history"`
	UpdatedAt    time.Time            `json:"updated_at"`
}

// ConsolidationFSM manages the 7-stage lifecycle transitions for memory items.
type ConsolidationFSM struct {
	mu      sync.RWMutex
	records map[string]MemoryLifecycleRecord
}

// NewConsolidationFSM initializes a new 7-state ConsolidationFSM.
func NewConsolidationFSM() *ConsolidationFSM {
	return &ConsolidationFSM{
		records: make(map[string]MemoryLifecycleRecord),
	}
}

// EvaluateTransition evaluates and advances the 7-state FSM for a memory item based on its age, usage, importance, and strength.
func (fsm *ConsolidationFSM) EvaluateTransition(item models.MemoryItem, now time.Time) MemoryLifecycleRecord {
	fsm.mu.Lock()
	defer fsm.mu.Unlock()

	rec, exists := fsm.records[item.ID]
	if !exists {
		rec = MemoryLifecycleRecord{
			MemoryID:     item.ID,
			CurrentStage: StageNew,
			TargetLayer:  item.Layer,
			Importance:   item.Importance,
			Strength:     item.Strength,
			UsageCount:   item.UsageCount,
			History:      []ConsolidationStage{StageNew},
			UpdatedAt:    now,
		}
	}

	ageHours := math.Max(0, now.Sub(item.CreatedAt).Hours())
	strength := item.Strength
	if strength <= 0 {
		strength = 0.85
	}
	decayed := raemath.ComputeDecayedStrength(strength, item.UsageCount, ageHours, 0.02)

	nextStage := rec.CurrentStage
	targetLayer := item.Layer

	switch {
	case decayed < 0.12 && item.Importance < 0.25:
		nextStage = StagePruned
	case decayed < 0.28 && item.Importance < 0.45:
		nextStage = StageArchived
		targetLayer = models.LayerLTM
	case decayed < 0.45 && item.UsageCount == 0:
		nextStage = StageDecaying
	case item.Importance >= 0.78 || item.UsageCount >= 3:
		if rec.CurrentStage == StageNew || rec.CurrentStage == StageActive {
			nextStage = StageConsolidating
			targetLayer = models.LayerSemantic
		} else {
			nextStage = StageConsolidated
			if item.Importance >= 0.88 {
				targetLayer = models.LayerLTM
			} else {
				targetLayer = models.LayerSemantic
			}
		}
	default:
		nextStage = StageActive
	}

	if nextStage != rec.CurrentStage {
		rec.CurrentStage = nextStage
		rec.History = append(rec.History, nextStage)
	}
	rec.TargetLayer = targetLayer
	rec.Importance = item.Importance
	rec.Strength = decayed
	rec.UsageCount = item.UsageCount
	rec.UpdatedAt = now
	fsm.records[item.ID] = rec
	return rec
}

// EvaluateBatch evaluates FSM transitions across a slice of memories and returns stage distribution and records.
func (fsm *ConsolidationFSM) EvaluateBatch(items []models.MemoryItem, now time.Time) ([]MemoryLifecycleRecord, map[ConsolidationStage]int) {
	records := make([]MemoryLifecycleRecord, 0, len(items))
	counts := map[ConsolidationStage]int{
		StageNew:           0,
		StageActive:        0,
		StageConsolidating: 0,
		StageConsolidated:  0,
		StageDecaying:      0,
		StageArchived:      0,
		StagePruned:        0,
	}
	for _, it := range items {
		r := fsm.EvaluateTransition(it, now)
		records = append(records, r)
		counts[r.CurrentStage]++
	}
	return records, counts
}

// DreamInsight represents a cross-episode synthetic insight generated by DreamingWorker.
type DreamInsight struct {
	ID              string   `json:"id"`
	InsightType     string   `json:"insight_type"` // cross_episode_bridge, hypothesis, emergent_pattern
	Summary         string   `json:"summary"`
	SourceMemoryIDs []string `json:"source_memory_ids"`
	BridgeConcepts  []string `json:"bridge_concepts"`
	NoveltyScore    float64  `json:"novelty_score"`
	Confidence      float64  `json:"confidence"`
	CreatedAt       string   `json:"created_at"`
}

// RunDreamingCycle implements DreamingWorker from apps/memory_api/workers/memory_maintenance.py:
// selects high-importance memories across episodes/tags, discovers non-obvious conceptual bridges,
// and synthesizes DreamInsight artifacts for the Reflective layer.
func RunDreamingCycle(memories []models.MemoryItem, minImportance float64) []DreamInsight {
	if minImportance <= 0 {
		minImportance = 0.60
	}
	candidates := make([]models.MemoryItem, 0)
	for _, m := range memories {
		if m.Importance >= minImportance || len(memories) <= 5 {
			candidates = append(candidates, m)
		}
	}
	sort.Slice(candidates, func(i, j int) bool {
		return candidates[i].Importance > candidates[j].Importance
	})
	if len(candidates) > 16 {
		candidates = candidates[:16]
	}

	insights := make([]DreamInsight, 0)
	nowStr := time.Now().UTC().Format(time.RFC3339)

	for i := 0; i < len(candidates); i++ {
		for j := i + 1; j < len(candidates); j++ {
			a := candidates[i]
			b := candidates[j]
			sim := raemath.CalculateSemanticSimilarity(a.Content, b.Content)
			// Dreaming looks for moderate overlap (0.08 <= sim <= 0.65) bridging distinct episodes or layers
			if (sim >= 0.05 && sim <= 0.70) || a.SessionID != b.SessionID || a.Layer != b.Layer {
				bridges := extractSharedOrBridgeTokens(a.Content, b.Content)
				novelty := math.Round((1.0-math.Abs(sim-0.35))*10000) / 10000
				conf := math.Round(((a.Importance+b.Importance)/2.0)*10000) / 10000
				insights = append(insights, DreamInsight{
					ID:              models.GenerateUUIDv7(),
					InsightType:     "cross_episode_bridge",
					Summary:         fmt.Sprintf("Dream synthesis bridging [%s] and [%s] via concepts (%s): potential architectural invariant.", truncateText(a.Content, 48), truncateText(b.Content, 48), strings.Join(bridges, ", ")),
					SourceMemoryIDs: []string{a.ID, b.ID},
					BridgeConcepts:  bridges,
					NoveltyScore:    novelty,
					Confidence:      conf,
					CreatedAt:       nowStr,
				})
				if len(insights) >= 6 {
					return insights
				}
			}
		}
	}

	if len(insights) == 0 && len(candidates) > 0 {
		c := candidates[0]
		insights = append(insights, DreamInsight{
			ID:              models.GenerateUUIDv7(),
			InsightType:     "hypothesis",
			Summary:         fmt.Sprintf("Autonomous hypothesis synthesized from anchor memory [%s]", truncateText(c.Content, 64)),
			SourceMemoryIDs: []string{c.ID},
			BridgeConcepts:  extractSharedOrBridgeTokens(c.Content, c.Content),
			NoveltyScore:    0.75,
			Confidence:      math.Max(0.7, c.Importance),
			CreatedAt:       nowStr,
		})
	}
	return insights
}

// CommunitySummary represents an executive summary of a Leiden/Louvain graph community.
type CommunitySummary struct {
	CommunityID  string   `json:"community_id"`
	NodeIDs      []string `json:"node_ids"`
	KeyThemes    []string `json:"key_themes"`
	SummaryText  string   `json:"summary_text"`
	Cohesion     float64  `json:"cohesion"`
}

// SummarizeCommunities implements CommunitySummarizer (apps/memory_api/services/community_summarizer.py).
func SummarizeCommunities(communities [][]string, memories []models.MemoryItem) []CommunitySummary {
	memByID := make(map[string]models.MemoryItem, len(memories))
	for _, m := range memories {
		memByID[m.ID] = m
	}

	out := make([]CommunitySummary, 0, len(communities))
	for idx, comm := range communities {
		themes := make([]string, 0)
		seen := make(map[string]struct{})
		snippets := make([]string, 0)
		for _, nodeID := range comm {
			if m, ok := memByID[nodeID]; ok {
				snippets = append(snippets, truncateText(m.Content, 40))
				for _, t := range m.Tags {
					if _, ok := seen[t]; !ok {
						seen[t] = struct{}{}
						themes = append(themes, t)
					}
				}
			} else {
				if _, ok := seen[nodeID]; !ok {
					seen[nodeID] = struct{}{}
					themes = append(themes, nodeID)
				}
			}
		}
		if len(themes) == 0 {
			themes = append(themes, "domain-cluster")
		}
		summary := fmt.Sprintf("Community #%d (%d nodes) centered on themes [%s]. Evidence: %s",
			idx+1, len(comm), strings.Join(themes, ", "), strings.Join(snippets, "; "))
		cohesion := math.Min(1.0, math.Round((0.60+0.05*float64(len(comm)))*10000)/10000)
		out = append(out, CommunitySummary{
			CommunityID: fmt.Sprintf("comm-%d", idx+1),
			NodeIDs:     comm,
			KeyThemes:   themes,
			SummaryText: summary,
			Cohesion:    cohesion,
		})
	}
	return out
}

// SummarizeSession implements SummarizationWorker (apps/memory_api/workers/summarization_worker.py):
// condenses long episodic/working sessions into a structured semantic summary item.
func SummarizeSession(sessionID string, project string, memories []models.MemoryItem) map[string]interface{} {
	sessionMems := make([]models.MemoryItem, 0)
	for _, m := range memories {
		if sessionID == "" || m.SessionID == sessionID {
			sessionMems = append(sessionMems, m)
		}
	}
	if len(sessionMems) == 0 {
		sessionMems = memories
	}
	topics := make([]string, 0)
	seen := make(map[string]struct{})
	highlights := make([]string, 0)
	for _, m := range sessionMems {
		if len(highlights) < 4 {
			highlights = append(highlights, truncateText(m.Content, 50))
		}
		for _, tag := range m.Tags {
			if _, ok := seen[tag]; !ok {
				seen[tag] = struct{}{}
				topics = append(topics, tag)
			}
		}
	}
	summaryText := fmt.Sprintf("Session [%s] summary (%d events): %s", sessionID, len(sessionMems), strings.Join(highlights, " | "))
	return map[string]interface{}{
		"session_id":       sessionID,
		"project":          project,
		"events_processed": len(sessionMems),
		"key_topics":       topics,
		"summary":          summaryText,
		"target_layer":     models.LayerSemantic,
	}
}

func extractSharedOrBridgeTokens(a, b string) []string {
	words := strings.Fields(strings.ToLower(a + " " + b))
	out := make([]string, 0, 4)
	seen := make(map[string]struct{})
	for _, w := range words {
		w = strings.Trim(w, ".,:;!?()[]{}\"'")
		if len(w) >= 5 {
			if _, ok := seen[w]; !ok {
				seen[w] = struct{}{}
				out = append(out, w)
				if len(out) >= 4 {
					break
				}
			}
		}
	}
	if len(out) == 0 {
		out = append(out, "architecture", "invariant")
	}
	return out
}

func truncateText(s string, maxLen int) string {
	s = strings.TrimSpace(s)
	if len(s) <= maxLen {
		return s
	}
	return s[:maxLen] + "..."
}
